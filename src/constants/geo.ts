export const PROVINCE_NAMES = Object.keys(PROVINCES)

export function citiesOf(province?: string | null): string[] {
  if (!province) return []
  return PROVINCES[province] ?? []
}

export function isValidProvinceCity(province?: string | null, city?: string | null): boolean {
  if (!province && !city) return true
  if (!province) return false
  const cities = PROVINCES[province]
  if (!cities) return false
  if (!city) return true
  return cities.includes(city)
}
