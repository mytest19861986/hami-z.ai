#!/bin/bash
# ============================================================================
# dev.sh — استارتاپ dev با بازیابی خودکار دیتابیس (SANDBOX-RECOVERY)
# ============================================================================
# سندباکس با `npm run dev` بالا می‌آید اما هنگام بازیابی، db/custom.db
# (untracked) را حذف و یک دیتابیس خالی فقط-شِما می‌سازد → خطای 500 در ورود.
# این اسکریپت قبل از بالا آوردن next dev، دیتابیس را در صورت نیاز از
# اسنپ‌شات tracked (db/snapshots/custom-snapshot.db) بازیابی می‌کند.
# ============================================================================
set -euo pipefail

cd "$(dirname "$0")/.."

# بازیابی در صورت نیاز (خاموش: فقط دیتابیس، سرور را خودمان بالا می‌آوریم)
if [ -f scripts/restore-db.sh ]; then
  bash scripts/restore-db.sh --no-serve || {
    echo "⚠️  بازیابی دیتابیس ناموفق بود؛ با دیتابیس فعلی ادامه می‌دهیم"
  }
fi

exec next dev -p 3000 2>&1 | tee dev.log
